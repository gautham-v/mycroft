    /// OPENDISPATCH_RAW_NS=62,63 OPENDISPATCH_RAW_AUDIT=<audit dir with raw/<n>.html and urls.txt> OPENDISPATCH_RAW_OUT=<dir>:
    /// extracts saved pages (no network) with the real Readability and writes <dir>/<n>.json (manual check only).
    @Test @MainActor func rawPages() async throws {
        let env = ProcessInfo.processInfo.environment
        guard let ns = env["OPENDISPATCH_RAW_NS"], let audit = env["OPENDISPATCH_RAW_AUDIT"], let dir = env["OPENDISPATCH_RAW_OUT"] else { return }
        let urls = try String(contentsOfFile: "\(audit)/urls.txt", encoding: .utf8).split(separator: "\n", omittingEmptySubsequences: false).map(String.init)
        try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
        let extraction = ArticleExtraction(readability: WebKitReadability(timeout: 30))
        for n in ns.split(separator: ",").compactMap({ Int($0) }) {
            let src = env["OPENDISPATCH_RAW_SRC"] ?? "\(audit)/raw"
            guard let raw = try? String(contentsOfFile: "\(src)/\(n).html", encoding: .utf8) else { continue }
            let out = try await extraction.extract(html: raw, pageURL: urls[n])
            let record: [String: Any] = ["url": urls[n], "lead": out.leadImage ?? NSNull(), "html": out.contentHtml ?? NSNull()]
            FileManager.default.createFile(atPath: "\(dir)/\(n).json", contents: try JSONSerialization.data(withJSONObject: record, options: [.prettyPrinted]))
        }
    }

    /// OPENDISPATCH_CLEAN_NS=38,39 OPENDISPATCH_RAW_AUDIT=<audit dir with out/<n>.json> OPENDISPATCH_RAW_OUT=<dir>: runs the cleanup
    /// on an earlier extraction (manual check only).
    @Test func cleanedOutputs() throws {
        let env = ProcessInfo.processInfo.environment
        guard let ns = env["OPENDISPATCH_CLEAN_NS"], let audit = env["OPENDISPATCH_RAW_AUDIT"], let dir = env["OPENDISPATCH_RAW_OUT"] else { return }
        try FileManager.default.createDirectory(atPath: dir, withIntermediateDirectories: true)
        for n in ns.split(separator: ",").compactMap({ Int($0) }) {
            guard let data = FileManager.default.contents(atPath: "\(audit)/out/\(n).json"),
                  let old = try? JSONSerialization.jsonObject(with: data) as? [String: Any], let html = old["html"] as? String else { continue }
            let out = ArticleSanitizer.sanitize(ArticlePasses.cleanArticle(html, base: old["url"] as? String))
            let record: [String: Any] = ["url": old["url"] ?? "", "html": out]
            FileManager.default.createFile(atPath: "\(dir)/\(n).json", contents: try JSONSerialization.data(withJSONObject: record, options: [.prettyPrinted]))
        }
    }
